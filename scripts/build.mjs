import {build} from 'esbuild';
import {mkdir,rm,cp,readdir,writeFile,readFile} from 'node:fs/promises';
import {dirname,join,relative} from 'node:path';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
await rm('dist',{recursive:true,force:true}); await mkdir('dist/assets',{recursive:true});
await build({entryPoints:{app:'field/app.js','runtime-worker':'field/runtime-worker.js'},bundle:true,format:'esm',splitting:true,platform:'browser',target:['safari18'],outdir:'dist/assets',chunkNames:'chunks/[name]-[hash]',minify:true,legalComments:'eof'});
await cp('field/index.html','dist/index.html'); await cp('field/style.css','dist/style.css');
await cp('icons','dist/icons',{recursive:true}); await cp('field/manifest.webmanifest','dist/manifest.webmanifest');
const require = createRequire(import.meta.url);
const transformerRequire = createRequire(require.resolve('@huggingface/transformers'));
const ortDir = dirname(transformerRequire.resolve('onnxruntime-web'));
await mkdir('dist/vendor/ort',{recursive:true});
for (const name of await readdir(ortDir)) if (/\.(wasm|mjs)$/.test(name)) await cp(join(ortDir,name),join('dist/vendor/ort',name));
const pdfRoot = dirname(dirname(require.resolve('pdfjs-dist')));
await mkdir('dist/vendor',{recursive:true});
await cp(join(pdfRoot,'build/pdf.worker.min.mjs'),'dist/vendor/pdf.worker.min.mjs');
async function files(dir) { let out=[]; for (const d of await readdir(dir,{withFileTypes:true})) { const p=join(dir,d.name); out.push(...(d.isDirectory() ? await files(p):[p])); } return out; }
let paths = (await files('dist')).map(p=>'./'+relative('dist',p).replaceAll('\\','/'));
const runtime = paths.filter(p=>p.includes('/vendor/ort/'));
await writeFile('dist/runtime-assets.json',JSON.stringify(runtime));
const shell = paths.filter(p=>!runtime.includes(p)).concat(['./','./runtime-assets.json','./asset-manifest.json']);
await writeFile('dist/asset-manifest.json',JSON.stringify(shell));
let digest = createHash('sha256');
for (const p of (await files('dist')).sort()) digest.update(await readFile(p));
const hash = digest.digest('hex').slice(0,12);
const sw = (await readFile('field/sw-template.js','utf8')).replace('__BUILD__',hash).replace('__SHELL__',JSON.stringify(shell));
await writeFile('dist/sw.js',sw);
await writeFile('dist/build.json',JSON.stringify({version:'2.0.0-beta.1',build:hash,commit:process.env.GITHUB_SHA || 'local'}));
await cp('README.md','dist/README.txt');
console.log('Built MAIA',hash,'shell:',shell.length,'runtime assets:',runtime.length);
